import { getFile } from './storage.js';
import { extension, fileSize, IMAGE_TYPES } from './files.js';
import { estimateCost } from './usage.js';
export const element = (tag, className, content) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (content !== undefined) node.textContent = content;
  return node;
};
export function button(label, action, className = 'text-button') {
  const node = element('button', className, label);
  node.type = 'button';
  node.onclick = action;
  return node;
}
export function download(blob, name) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = name.replace(/[\\/\r\n]/g, '_');
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 30000);
}
const previews = new Set();
export function clearPreviews() {
  previews.forEach((url) => URL.revokeObjectURL(url));
  previews.clear();
}
export function attachmentCard(attachment, onRemove) {
  const card = element('div', 'attachment');
  if (attachment.source === 'generated' && IMAGE_TYPES[extension(attachment.name)])
    card.classList.add('generated-image');
  const icon = element('span', 'file-icon', extension(attachment.name).slice(0, 5).toUpperCase());
  card.append(icon);
  const info = element('div', 'attachment-info');
  const name = element('div', 'attachment-name', attachment.name);
  name.title = attachment.name;
  const meta = element(
    'div',
    'attachment-meta',
    `${fileSize(attachment.size)} · ${attachment.source === 'generated' ? 'Generated by a tool' : 'Attachment'}`,
  );
  info.append(name, meta);
  card.append(info);
  const save = button('↓', async () => {
    const file = await getFile(attachment.id);
    if (file?.blob) download(file.blob, attachment.name);
  });
  save.title = `Download ${attachment.name}`;
  save.setAttribute('aria-label', save.title);
  card.append(save);
  if (onRemove) {
    const remove = button('×', onRemove);
    remove.setAttribute('aria-label', `Remove ${attachment.name}`);
    card.append(remove);
  }
  getFile(attachment.id)
    .then((file) => {
      if (!file?.blob) {
        meta.textContent = 'No local copy available';
        save.disabled = true;
        return;
      }
      if (IMAGE_TYPES[extension(attachment.name)] && file.blob.size < 33 * 1024 * 1024) {
        const img = element('img');
        img.alt = attachment.name;
        const url = URL.createObjectURL(file.blob);
        previews.add(url);
        img.src = url;
        icon.replaceWith(img);
      }
    })
    .catch(() => {
      meta.textContent = 'Could not read the file';
      save.disabled = true;
    });
  return card;
}
let markdown;
export function renderMarkdown(container, text) {
  markdown ||= window.markdownit({ html: false, linkify: true, breaks: true });
  container.innerHTML = markdown.render(text || '');
  for (const link of container.querySelectorAll('a')) {
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
  }
  for (const pre of container.querySelectorAll('pre')) {
    const code = pre.querySelector('code');
    const copy = button(
      'Copy',
      async () => {
        await navigator.clipboard.writeText(code.textContent);
        copy.textContent = 'Copied';
      },
      'code-copy',
    );
    pre.append(
      element('span', 'code-lang', (code.className || '').replace('language-', '') || 'code'),
      copy,
    );
  }
  for (const table of container.querySelectorAll('table')) {
    const wrapper = element('div', 'table-wrap');
    table.replaceWith(wrapper);
    wrapper.append(table);
  }
}
export function messageCard(message, actions) {
  const card = element('article', `message ${message.role}`);
  card.dataset.id = message.id;
  const header = element('header', 'message-header');
  header.append(
    element('span', 'role-marker', message.role === 'user' ? 'U' : 'n'),
    element(
      'strong',
      '',
      message.role === 'user' ? 'You' : message.role === 'assistant' ? 'Assistant' : 'Developer',
    ),
  );
  if (message.model) header.append(element('span', 'subtle', message.model));
  card.append(header);
  const body = element('div', 'message-body');
  if (message.role === 'user') body.textContent = message.text;
  else renderMarkdown(body, message.text);
  card.append(body);
  const files = element('div', 'attachments');
  [...(message.attachments || []), ...(message.artifacts || [])].forEach((a) =>
    files.append(attachmentCard(a)),
  );
  card.append(files);
  if (message.citations?.length) {
    const sources = element('div', 'citations');
    message.citations
      .filter((c) => /^https?:\/\//i.test(c.url))
      .forEach((c, i) => {
        const link = element('a', '', `${i + 1}. ${c.title || new URL(c.url).hostname}`);
        link.href = c.url;
        link.target = '_blank';
        link.rel = 'noopener noreferrer';
        sources.append(link);
      });
    card.append(sources);
  }
  const footer = element('footer', 'message-footer');
  footer.append(button('Copy', async () => navigator.clipboard.writeText(message.text)));
  if (message.role === 'user') footer.append(button('Edit', () => actions.edit(message.id)));
  if (actions.retry) footer.append(button('Regenerate', actions.retry));
  if (message.role === 'assistant' && message.text)
    footer.append(
      button('↓ Text', () =>
        download(new Blob([message.text], { type: 'text/plain' }), 'response.txt'),
      ),
    );
  if (message.status && message.status !== 'complete')
    footer.append(
      element(
        'span',
        'message-state',
        {
          preparing: 'Preparing…',
          streaming: 'Generating…',
          cancelled: 'Stopped',
          interrupted: 'Interrupted',
          error: 'Error · you can retry',
          incomplete: 'Output limit reached',
        }[message.status] || message.status,
      ),
    );
  if (message.usage) {
    const cost = estimateCost(message);
    const usage = element(
      'span',
      'message-usage',
      `${(message.usage.input_tokens || 0).toLocaleString()} in  ·  ${(message.usage.output_tokens || 0).toLocaleString()} out${cost !== null ? ` · ≈ $${cost.toFixed(4)}` : ''}`,
    );
    usage.title =
      'Estimated token cost at standard USD rates (September 12, 2026). Excludes tools and regional surcharges.';
    footer.append(usage);
  }
  card.append(footer);
  return card;
}
